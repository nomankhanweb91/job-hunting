/**
 * Generates the complete default TargetRolesConfig with 160 standard roles
 */
export function generateDefaultTargetRolesConfig(): TargetRolesConfig {
  const roles: TargetRoleItem[] = [];

  let roleIndex = 1;
  for (const cat of ROLE_CATEGORIES) {
    for (const roleName of cat.roles) {
      roles.push({
        id: `role-${roleIndex++}-${roleName.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
        name: roleName,
        category: cat.name,
        enabled: true,
        priority: cat.defaultPriority,
        isCustom: false,
      });
    }
  }

  return {
    roles,
    preferredRoles: [
      'Lead UI/UX Designer',
      'Senior Product Designer',
      'Product Design Lead',
      'Design Systems Lead',
      'Principal Product Designer',
      'UI/UX Lead',
      'Senior UI/UX Designer',
    ],
    excludedRoles: [
      'Automotive Embedded C++ Firmware Engineer',
      'Telecaller',
      'Data Entry Operator',
      'Civil Site Engineer',
      'Sales Executive',
      'Manual QA Tester',
    ],
    preferredKeywords: [
      'Design Systems',
      'Figma',
      'Tokens Studio',
      'Fintech',
      'Mobile UX',
      'SaaS',
      'Responsive Web',
      'User Research',
      'Wireframing',
      'Prototyping',
      'Conversion Rate Optimization',
      'Shopify',
      'WordPress',
    ],
    excludedKeywords: [
      'Internship',
      'Unpaid',
      'Cold Calling',
      'Embedded C++',
      'Hardware Engineer',
      'Civil Engineering',
      'Nurse',
      'Data Entry',
      'Commission Only',
      'Night Shift Only',
    ],
  };
}
